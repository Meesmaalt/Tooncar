export function createCircuitCurve(points: CircuitPoint[]) {
  const curve = new THREE.CatmullRomCurve3(points.map(p => new THREE.Vector3(...p)), true, 'centripetal');
  // Three's default 200-entry arc table is insufficient for long, twisting roads.
  curve.arcLengthDivisions = 4096;
  curve.updateArcLengths();
  return curve;
}
